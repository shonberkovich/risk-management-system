def test_list_audit_log_pagination_limit_and_offset(client, make_user):
    admin = make_user(role="ADMIN")
    headers = auth_headers(admin)
    for i in range(5):
        client.post("/api/properties", json=_property_payload(property_code=f"PRP-{i}"), headers=headers)

    page1 = client.get("/api/audit-log", params={"limit": 2, "offset": 0}, headers=headers).json()
    page2 = client.get("/api/audit-log", params={"limit": 2, "offset": 2}, headers=headers).json()

    assert len(page1["entries"]) == 2
    assert len(page2["entries"]) == 2
    assert page1["total"] == page2["total"]
    assert page1["total"] >= 5
    page1_ids = {e["log_id"] for e in page1["entries"]}
    page2_ids = {e["log_id"] for e in page2["entries"]}
    assert page1_ids.isdisjoint(page2_ids)


