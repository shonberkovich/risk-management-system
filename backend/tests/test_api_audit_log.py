"""Tests for routers/audit.py's read/filter/paginate surface over rows written
by app/middleware/audit.py. Real audit rows are generated by making actual
mutating requests through the test client (the middleware writes them as a
side effect), rather than inserting AuditLog rows by hand — this also
exercises the middleware's own entity_type/entity_id extraction end to end.
RBAC (401/403/200 for ADMIN-only) is already covered by test_api_permissions.py
and test_rbac_regression.py; this file focuses on filtering/pagination/shape.
"""
from __future__ import annotations

from tests.conftest import auth_headers


def _property_payload(**overrides) -> dict:
    payload = {
        "property_code": "PRP-AUDIT-001",
        "name": "נכס לבדיקת יומן ביקורת",
        "address": "רחוב הבדיקה 1",
        "region": "מרכז",
        "latitude": 32.08,
        "longitude": 34.78,
        "asset_type": "OFFICE_BUILDING",
        "replacement_value": 1_000_000,
        "book_value": 800_000,
    }
    payload.update(overrides)
    return payload


def test_list_audit_log_captures_create_and_update_actions(client, make_user):
    admin = make_user(role="ADMIN")
    headers = auth_headers(admin)

    created = client.post("/api/properties", json=_property_payload(), headers=headers).json()
    client.put(f"/api/properties/{created['property_id']}", json={"name": "שם מעודכן"}, headers=headers)

    resp = client.get("/api/audit-log", headers=headers)
    assert resp.status_code == 200
    body = resp.json()
    actions = [(e["entity_type"], e["action"]) for e in body["entries"]]
    assert ("PROPERTIES", "CREATE") in actions
    assert ("PROPERTIES", "UPDATE") in actions


def test_list_audit_log_orders_most_recent_first(client, make_user):
    admin = make_user(role="ADMIN")
    headers = auth_headers(admin)

    client.post("/api/properties", json=_property_payload(property_code="PRP-A"), headers=headers)
    client.post("/api/properties", json=_property_payload(property_code="PRP-B"), headers=headers)

    resp = client.get("/api/audit-log", headers=headers)
    entries = resp.json()["entries"]
    timestamps = [e["timestamp"] for e in entries]
    assert timestamps == sorted(timestamps, reverse=True)
    # The most recent create (PRP-B) must appear before the older one (PRP-A).
    log_ids_by_new_value_order = [e["log_id"] for e in entries]
    assert log_ids_by_new_value_order == sorted(log_ids_by_new_value_order, reverse=True)


